"""Labelled edge-case injection.

Baseline records are generated by the policy engine first (always correct). This module then
deliberately corrupts a small, counted set of records to simulate process failures. Every
corrupted record gets a row in ground truth (never in the input tables), so detection can be
measured. Candidates are chosen so that one anomaly never cascades into a second, unrelated
violation: each anomaly touches its own RMA, and orders that have several RMAs are avoided
(cumulative refund caps and prior-approved quantities are shared across sibling RMAs).

Two injection points:
  * decision anomalies (before downstream generation, so the wrong decision flows through):
      LATE_APPROVED_WITHOUT_OVERRIDE, QTY_EXCEEDS_PURCHASED
  * post-process anomalies (after downstream generation):
      REFUND_EXCEEDS_PAID, RESTOCK_BEFORE_INSPECTION, DUPLICATE_REFUND
"""
from datetime import timedelta

from . import config as C
from .money import fmt


def _shared_rmas(g):
    """RMAs whose order has another RMA - an anomaly there could leak into the sibling's checks."""
    per_order = {}
    for r in g.t["return_request"]:
        per_order.setdefault(r["order_id"], []).append(r["rma_id"])
    return {rma for rmas in per_order.values() if len(rmas) > 1 for rma in rmas}


def _record(g, issue, entity_type, entity_id, rma_id, related, expected, recorded, step, desc, return_lines=()):
    g.gt_anomalies.append({
        "anomaly_id": f"GT-{len(g.gt_anomalies) + 1:04d}", "issue_type": issue, "entity_type": entity_type,
        "entity_id": entity_id, "rma_id": rma_id, "related_ids": ";".join(related),
        "expected_value": expected, "recorded_value": recorded, "injected_at_step": step, "description": desc,
    })
    for rl_id in return_lines:
        label = g.gt_labels[rl_id]
        label["is_anomaly"] = True
        types = [t for t in label["anomaly_issue_types"].split(";") if t] + [issue]
        label["anomaly_issue_types"] = ";".join(types)


def inject_decision_anomalies(g):
    rng = g.rng("anomalies:decision")
    rl_by_id = {rl["return_line_id"]: rl for rl in g.t["return_line"]}
    used = _shared_rmas(g)

    # Late request approved although no manager override was recorded.
    cands = [al for al in g.t["authorization_line"] if al["decision_reason"] == "REJECT_LATE"]
    rng.shuffle(cands)
    n = 0
    for al in cands:
        if n >= g.anomaly_counts["LATE_APPROVED_WITHOUT_OVERRIDE"]:
            break
        rl = rl_by_id[al["return_line_id"]]
        if rl["rma_id"] in used:
            continue
        ol = g.order_lines[rl["order_line_id"]]
        qty = min(rl["requested_qty"], ol["qty"] - al["prior_approved_qty"])
        if qty <= 0:
            continue
        al.update(approved_qty=qty, line_decision="APPROVED", decision_reason="WITHIN_POLICY", override_applied=False)
        g.refresh_authorization(g.auth_by_rma[rl["rma_id"]])
        used.add(rl["rma_id"])
        n += 1
        _record(g, "LATE_APPROVED_WITHOUT_OVERRIDE", "authorization_line", al["authorization_line_id"], rl["rma_id"],
                [rl["return_line_id"], al["authorization_id"]], "REJECTED/REJECT_LATE", f"APPROVED qty={qty}",
                "decision", f"Requested {al['days_since_delivery']} days after delivery; window "
                f"{al['effective_window_days']} days; late_override_flag=false", [rl["return_line_id"]])

    # Approved quantity exceeds what was purchased.
    target = g.anomaly_counts["QTY_EXCEEDS_PURCHASED"]
    over, exact = [], []
    for al in g.t["authorization_line"]:
        rl = rl_by_id[al["return_line_id"]]
        ol = g.order_lines[rl["order_line_id"]]
        if al["prior_approved_qty"] or rl["rma_id"] in used:
            continue
        if al["decision_reason"] == "QTY_CAPPED" and rl["requested_qty"] > ol["qty"]:
            over.append(al)
        elif al["decision_reason"] == "WITHIN_POLICY" and rl["requested_qty"] == ol["qty"]:
            exact.append(al)
    rng.shuffle(over)
    rng.shuffle(exact)
    n = 0
    for al in over + exact:
        if n >= target:
            break
        rl = rl_by_id[al["return_line_id"]]
        if rl["rma_id"] in used:
            continue
        ol = g.order_lines[rl["order_line_id"]]
        if rl["requested_qty"] <= ol["qty"]:
            # Customer over-request is part of the scenario; the expected (correct) decision is re-derived.
            rl["requested_qty"] = ol["qty"] + rng.randint(1, 2)
            d = g.decide(g.requests[rl["rma_id"]], rl, 0)
            g.gt_labels[rl["return_line_id"]].update(
                expected_line_decision=d.line_decision, expected_approved_qty=d.approved_qty,
                expected_decision_reason=d.decision_reason)
        al.update(approved_qty=rl["requested_qty"], line_decision="APPROVED", decision_reason="WITHIN_POLICY")
        g.refresh_authorization(g.auth_by_rma[rl["rma_id"]])
        used.add(rl["rma_id"])
        n += 1
        _record(g, "QTY_EXCEEDS_PURCHASED", "authorization_line", al["authorization_line_id"], rl["rma_id"],
                [rl["return_line_id"], ol["order_line_id"]], f"approved_qty<={ol['qty']}",
                f"approved_qty={rl['requested_qty']}", "decision",
                f"Purchased {ol['qty']} units, requested {rl['requested_qty']}, approved {rl['requested_qty']}",
                [rl["return_line_id"]])


def inject_post_anomalies(g):
    rng = g.rng("anomalies:post")
    used = {a["rma_id"] for a in g.gt_anomalies} | _shared_rmas(g)
    lines_by_refund = {}
    for rf in g.t["refund_line"]:
        lines_by_refund.setdefault(rf["refund_id"], []).append(rf)
    paid_refunds_per_line = {}
    for ref in g.t["refund"]:
        if ref["paid_amount"] > 0:
            for rf in lines_by_refund[ref["refund_id"]]:
                paid_refunds_per_line[rf["order_line_id"]] = paid_refunds_per_line.get(rf["order_line_id"], 0) + 1

    def clean_paid_refunds():
        out = [r for r in g.t["refund"] if r["paid_amount"] > 0 and r["rma_id"] not in used
               and len(g.refunds_by_rma[r["rma_id"]]) == 1]
        rng.shuffle(out)
        return out

    # Refund line pays out more than the customer paid for the order line.
    n = 0
    for ref in clean_paid_refunds():
        if n >= g.anomaly_counts["REFUND_EXCEEDS_PAID"]:
            break
        lines = [rf for rf in lines_by_refund[ref["refund_id"]]
                 if rf["refund_qty"] > 0 and paid_refunds_per_line[rf["order_line_id"]] == 1]
        if not lines:
            continue
        rf = rng.choice(lines)
        ol = g.order_lines[rf["order_line_id"]]
        old_amount = ref["refund_amount"]
        new_line = ol["line_total"] + rng.randint(500, 5000)
        delta = new_line - rf["line_refund_amount"]
        rf["merchandise_amount"] += delta
        rf["line_refund_amount"] = new_line
        ref["lines_amount"] += delta
        ref["refund_amount"] += delta
        ref["paid_amount"] = ref["refund_amount"]
        used.add(ref["rma_id"])
        n += 1
        _record(g, "REFUND_EXCEEDS_PAID", "refund", ref["refund_id"], ref["rma_id"],
                [rf["refund_line_id"], ol["order_line_id"]], f"refund_amount={fmt(old_amount)}",
                f"refund_amount={fmt(ref['refund_amount'])}", "post",
                f"Line refund {fmt(new_line)} > paid {fmt(ol['line_total'])} for {ol['order_line_id']}",
                [rf["return_line_id"]])

    # Units restocked before the inspection happened.
    ins_by_id = {i["inspection_id"]: i for i in g.t["inspection"]}
    mov_by_disp = {m["disposition_id"]: m for m in g.t["inventory_movement"]}
    rma_of_line = {rl["return_line_id"]: rl["rma_id"] for rl in g.t["return_line"]}
    cands = [d for d in g.t["inventory_disposition"] if d["disposition"] == "RESTOCK"]
    rng.shuffle(cands)
    n = 0
    for d in cands:
        if n >= g.anomaly_counts["RESTOCK_BEFORE_INSPECTION"]:
            break
        rma_id = rma_of_line[d["return_line_id"]]
        if rma_id in used:
            continue
        ins = ins_by_id[d["inspection_id"]]
        d["decided_at"] = ins["inspected_at"] - timedelta(minutes=rng.randint(60, 48 * 60))
        mov_by_disp[d["disposition_id"]]["moved_at"] = d["decided_at"]
        used.add(rma_id)
        n += 1
        _record(g, "RESTOCK_BEFORE_INSPECTION", "inventory_disposition", d["disposition_id"], rma_id,
                [d["inspection_id"], mov_by_disp[d["disposition_id"]]["movement_id"]],
                f"decided_at>={ins['inspected_at'].isoformat()}", f"decided_at={d['decided_at'].isoformat()}",
                "post", "Stock moved to SELLABLE before the inspection record existed", [d["return_line_id"]])

    # Second payout for an already-paid RMA (idempotency control bypassed with a new key).
    n = 0
    for ref in clean_paid_refunds():
        if n >= g.anomaly_counts["DUPLICATE_REFUND"]:
            break
        requested_at = ref["processed_at"] + timedelta(days=rng.randint(1, 5), minutes=rng.randint(0, 600))
        processed_at = requested_at + timedelta(minutes=rng.randint(60, 24 * 60))
        if processed_at > C.AS_OF:
            continue
        rid = g.next_id("REF")
        dup = dict(ref, refund_id=rid, idempotency_key=f"{ref['rma_id']}:REFUND:2", attempt_seq=2,
                   requested_at=requested_at, processed_at=processed_at, blocked_reason=None)
        g.t["refund"].append(dup)
        g.refunds_by_rma[ref["rma_id"]].append(dup)
        for k, rf in enumerate(lines_by_refund[ref["refund_id"]], 1):
            g.t["refund_line"].append(dict(rf, refund_line_id=f"REFL-{rid}-{k:02d}", refund_id=rid))
        g.event("REFUND", rid, None, "REQUESTED", requested_at, "SYSTEM", reason=dup["idempotency_key"])
        g.event("REFUND", rid, "REQUESTED", "PAID", processed_at, "PAYMENT_GATEWAY")
        used.add(ref["rma_id"])
        n += 1
        _record(g, "DUPLICATE_REFUND", "refund", rid, ref["rma_id"], [ref["refund_id"]], "BLOCKED_DUPLICATE",
                f"PAID {fmt(dup['paid_amount'])}", "post",
                f"Second payout for {ref['rma_id']}; original {ref['refund_id']} already PAID",
                [rf["return_line_id"] for rf in lines_by_refund[ref["refund_id"]]])
